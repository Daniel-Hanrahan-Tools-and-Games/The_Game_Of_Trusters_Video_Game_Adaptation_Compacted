-- =========================================
-- Trap System
-- =========================================
function trap()
    local trapIntelligence = math.random(1,10)
    local escapeRoll = D20()
    if escapeRoll > trapIntelligence then
        message="Your party escaped the trap."
    else
        message="Your party did not escape. Game Over."
        gameOver=true
    end
    gameState="message"
end

-- =========================================
-- Fusion System
-- =========================================
-- increases power after fusion
function fuse(a,b)
    local f = {}
    f.name = a.name.."-"..b.name
    f.hp = 1
    f.attack = a.attack + b.attack
    f.stats = {}
    for k,v in pairs(a.stats) do f.stats[k]=v end
    for k,v in pairs(b.stats) do f.stats[k]=v end
    if a.stats.element=="Fire" and b.stats.element=="Ice" then
        f.stats.ability="Steam Blast"
    end
    return f
end

-- checks if player is fused
function fusionEvent()
    if #player.units < 2 then return end
    if D6() >= 4 then
        local i1 = math.random(#player.units)
        local i2 = i1
        while i2 == i1 do i2 = math.random(#player.units) end
        local u1 = player.units[i1]
        local u2 = player.units[i2]
        local fused = fuse(u1,u2)
        if i1 > i2 then
            table.remove(player.units,i1)
            table.remove(player.units,i2)
        else
            table.remove(player.units,i2)
            table.remove(player.units,i1)
        end
        table.insert(player.units,fused)
        message = "Fusion: "..u1.name.." + "..u2.name.." -> "..fused.name
        gameState="message"
    end
end

-- =========================================
-- Spawn Enemy
-- =========================================
