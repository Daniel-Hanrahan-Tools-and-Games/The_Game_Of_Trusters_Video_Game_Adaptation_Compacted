-- =========================================
-- Dice Functions
-- =========================================
function D20() return math.random(1,25) end
function D12() return math.random(1,12) end
function D10() return math.random(1,10) end
function D8()  return math.random(1,8)  end
function D6()  return math.random(1,6)  end
function D4()  return math.random(1,4)  end

-- =========================================
-- Player and Unit/rest of party Structures
-- =========================================
function createUnit(name, attack, stats)
    return {name=name, hp=1, attack=attack, stats=stats or {}}
end

local player = {
    name="Hero",
    units={
        createUnit("Fire",10,{element="Fire"}),
        createUnit("Ice",8,{element="Ice"})
    },
    inventory={}
}

