function updateEnemy()
    if gameState~="enemy" or not currentEnemy or gameOver then return end
    if keyp(49) then currentEnemy.action=0; gameState="enemy_action" end -- Attack
    if keyp(50) then currentEnemy.action=1; gameState="enemy_action" end -- Talk
end

-- =========================================
-- Enemy Action Resolution
-- =========================================
function handleEnemyAction()
    if gameState~="enemy_action" or not currentEnemy then return end

    if currentEnemy.action==0 then
    				-- this part does not work from what I have tested
        currentEnemy.rollResult=D20()
        if currentEnemy.rollResult > currentEnemy.strength then
            message="You defeated "..currentEnemy.name.."!"
        else
            message="You were defeated. Game Over."
            gameOver=true
        end
    -- makes sure the game works as intended and the results it needs to be greater than is the roll results divided by 20    
    else
        currentEnemy.rollResult = (currentEnemy.trust==1 and D12()) or
                                  (currentEnemy.trust==2 and D6()) or
                                  (currentEnemy.trust==3 and D4())
        local success = (currentEnemy.trust==1 and currentEnemy.rollResult>7) or
                        (currentEnemy.trust==2 and currentEnemy.rollResult>4) or
                        (currentEnemy.trust==3 and currentEnemy.rollResult>2)
        if success then
            message="You took out"..currentEnemy.name.."."
        else
            message="Game Over."
            gameOver=true
        end
    end
    currentEnemy=nil
    gameState="message"
end

-- =========================================
-- Room Navigation
-- =========================================
function updateRoom()
				-- randomizes choices
    if gameState~="room" or gameOver then return end
    local room = roomTemplates[currentRoom]
    for i,_ in ipairs(room.choices) do
        if keyp(48+i) then -- top-row keys 1-5
            currentRoom=roomTypes[math.random(#roomTypes)]
            message="You chose option "..i
            handleEvent()
        end
    end
end

-- =========================================
-- Continue after messages
-- =========================================
-- checks if messages are displaying properly
function updateMessage()
    if gameState~="message" or gameOver then return end
    for i=49,53 do
        if keyp(i) then
            gameState="room"
            message=""
        end
    end
end

