function spawnEnemy()
    currentEnemy = {
        name = enemyTypes[math.random(#enemyTypes)],
        outline = outlineColors[math.random(#outlineColors)],
        color = outlineColors[math.random(#outlineColors)],
        strength = math.random(1,10),
        trust = math.random(1,3),
        action = nil,
        rollResult = nil
    }
    message = "Encountered: "..currentEnemy.name..
              "\nOutline: "..currentEnemy.outline..
              "\nColor: "..currentEnemy.color..
              "\nPress 1=Attack, 2=Talk"
    gameState="enemy"
end

-- =========================================
-- Handle Room Events
-- =========================================
-- messages for what has happened to player
function handleEvent()
    local roll = D6()
    if roll <= 2 then
        message="Nothing happens."
        gameState="message"
    elseif roll <= 4 then
        table.insert(player.inventory,"Gold Coin")
        message="You found a Gold Coin!"
        gameState="message"
    else
        spawnEnemy()
    end
    fusionEvent()
end

-- =========================================
-- Enemy Input Handling
-- =========================================
